# frozen_string_literal: true

# The `bots` index is shared with the data pre-processing pipeline
# (`compass_contributor/bot.py` in compass-metrics-model). The pipeline loads
# every document of the requested platform and splits them into three scopes:
#
#   * common    -> `community` and `repo` are empty, the contributor matches
#                  every repository of the platform (the configured values are
#                  regular expressions, e.g. `^.*bot$`)
#   * community -> only `community` is set, the contributor matches every
#                  repository whose url contains the community address
#   * repo      -> `community` and `repo` are set, the contributor matches that
#                  single repository only
#
# Robots that the automatic detection missed can be tagged manually through the
# `manageContributorBot` mutation. The tag is written into this index so the
# next analysis run of the repository reports the contributor as a robot too.
class Bot < BaseIndex

  # The pipeline does not paginate while flattening the bot list, so keep the
  # same upper bound here to make sure manually tagged robots are never missed.
  MAX_PER_PAGE = 10_000

  def self.index_name
    'bots'
  end

  def self.mapping
    {"properties"=>
      {"community"=>{"type"=>"text", "fields"=>{"keyword"=>{"type"=>"keyword", "ignore_above"=>256}}},
       "contributor"=>{"type"=>"text", "fields"=>{"keyword"=>{"type"=>"keyword", "ignore_above"=>256}}},
       "id"=>{"type"=>"text", "fields"=>{"keyword"=>{"type"=>"keyword", "ignore_above"=>256}}},
       "modify_by"=>{"type"=>"text", "fields"=>{"keyword"=>{"type"=>"keyword", "ignore_above"=>256}}},
       "platform_type"=>{"type"=>"text", "fields"=>{"keyword"=>{"type"=>"keyword", "ignore_above"=>256}}},
       "repo"=>{"type"=>"text", "fields"=>{"keyword"=>{"type"=>"keyword", "ignore_above"=>256}}},
       "update_at_date"=>{"type"=>"date"},
       "uuid"=>{"type"=>"text", "fields"=>{"keyword"=>{"type"=>"keyword", "ignore_above"=>256}}}}}
  end

  # The document id must stay identical to the one generated by the pipeline
  # (`get_uuid(contributor, platform_type)`), otherwise importing the bot
  # configuration again would duplicate every manually created tag.
  def self.document_id(contributor, platform_type)
    Digest::SHA1.hexdigest([contributor, platform_type].join(':'))
  end

  # Translate the `label`/`level` pair used by the web service into the scope
  # fields of the `bots` index. A community tag is stored without a `repo` so it
  # applies to every repository of the community, while a repo tag only applies
  # to the repository itself.
  def self.scope_attributes(level, label)
    if level.to_s.downcase == 'community'
      { 'community' => label, 'repo' => nil }
    else
      { 'community' => nil, 'repo' => label }
    end
  end

  # Build the document written into the `bots` index. It is kept separate from
  # `tag` so the payload can be asserted without a running OpenSearch cluster.
  def self.tag_record(contributor:, platform_type:, level:, label:, operator: nil)
    scope = scope_attributes(level, label)
    uuid = document_id(contributor, platform_type)
    OpenStruct.new(
      {
        id: uuid,
        uuid: uuid,
        contributor: contributor,
        platform_type: platform_type,
        community: scope['community'],
        repo: scope['repo'],
        modify_by: operator,
        update_at_date: Time.current
      }
    )
  end

  # Store the manual tag and return the record that has been written.
  def self.tag(contributor:, platform_type:, level:, label:, operator: nil)
    record =
      tag_record(
        contributor: contributor,
        platform_type: platform_type,
        level: level,
        label: label,
        operator: operator
      )
    import(record)
    record
  end

  # Remove the manual tag of a contributor. The document id only depends on the
  # contributor and the platform on purpose: the pipeline treats a contributor
  # as a robot for a whole data source, so a single document is enough.
  def self.untag(contributor, platform_type)
    self
      .must(term: { 'uuid.keyword' => document_id(contributor, platform_type) })
      .delete
  end

  # Return the contributors of the given repositories that are stored in the
  # `bots` index. The scope of every tag is evaluated in Ruby to stay consistent
  # with the pipeline, which matches a community by substring of the repository
  # url and a repository by its full url.
  def self.tagged_contributors(repo_urls:, community: nil, platform_type: nil)
    base = self.per(MAX_PER_PAGE)
    base = base.must(match_phrase: { 'platform_type.keyword' => platform_type }) if platform_type.present?
    sources = base.execute.raw_response.dig('hits', 'hits')&.map { |hit| hit['_source'] } || []
    indexed_contributors(sources, repo_urls: repo_urls, community: community)
  end

  # Pure helper, separated from the OpenSearch query so it can be unit tested
  # without a running cluster.
  def self.indexed_contributors(sources, repo_urls:, community: nil)
    repo_urls = Array(repo_urls)
    sources.each_with_object(Set.new) do |source, contributors|
      contributor = source['contributor']
      next if contributor.blank?

      tag_community = source['community']
      tag_repo = source['repo']
      if tag_community.blank? && tag_repo.blank?
        contributors << contributor
      elsif tag_repo.blank?
        matched = repo_urls.any? { |repo_url| repo_url.include?(tag_community) }
        matched ||= community.present? && community == tag_community
        contributors << contributor if matched
      elsif repo_urls.include?(tag_repo)
        contributors << contributor
      end
    end
  end
end
