# frozen_string_literal: true

require 'rails_helper'

RSpec.describe Bot, type: :model do
  describe '.document_id' do
    it 'is stable for the same contributor and platform' do
      expect(described_class.document_id('k8s-ci-robot', 'github'))
        .to eq(described_class.document_id('k8s-ci-robot', 'github'))
    end

    it 'matches the id generated by the data pre-processing pipeline' do
      # compass-metrics-model builds the id with `get_uuid(contributor,
      # platform_type)`, i.e. the sha1 of the values joined by a colon.
      expect(described_class.document_id('k8s-ci-robot', 'github'))
        .to eq(Digest::SHA1.hexdigest('k8s-ci-robot:github'))
    end

    it 'depends on the platform' do
      expect(described_class.document_id('openharmony_ci', 'gitee'))
        .not_to eq(described_class.document_id('openharmony_ci', 'github'))
    end
  end

  describe '.scope_attributes' do
    it 'stores a community tag without a repo' do
      expect(described_class.scope_attributes('community', 'https://gitee.com/openharmony'))
        .to eq({ 'community' => 'https://gitee.com/openharmony', 'repo' => nil })
    end

    it 'stores a repo tag with the repository url' do
      expect(described_class.scope_attributes('repo', 'https://github.com/kubernetes/kubernetes'))
        .to eq({ 'community' => nil, 'repo' => 'https://github.com/kubernetes/kubernetes' })
    end

    it 'falls back to the repo scope for unknown levels' do
      expect(described_class.scope_attributes('project', 'https://github.com/pytorch/pytorch'))
        .to eq({ 'community' => nil, 'repo' => 'https://github.com/pytorch/pytorch' })
    end
  end

  describe '.tag_record' do
    let(:record) do
      described_class.tag_record(
        contributor: 'Kubernetes Submit Queue',
        platform_type: 'github',
        level: 'repo',
        label: 'https://github.com/kubernetes/kubernetes',
        operator: 42
      )
    end

    it 'builds a document with the pipeline compatible id' do
      expect(record.id).to eq(Digest::SHA1.hexdigest('Kubernetes Submit Queue:github'))
      expect(record.uuid).to eq(record.id)
    end

    it 'stores the scope of the tag' do
      expect(record.contributor).to eq('Kubernetes Submit Queue')
      expect(record.platform_type).to eq('github')
      expect(record.repo).to eq('https://github.com/kubernetes/kubernetes')
      expect(record.community).to be_nil
    end

    it 'keeps track of the operator and the update time' do
      expect(record.modify_by).to eq(42)
      expect(record.update_at_date).to be_present
    end
  end

  describe '.indexed_contributors' do
    let(:common_tag) do
      { 'contributor' => 'openeuler-ci-bot', 'community' => nil, 'repo' => nil }
    end

    let(:community_tag) do
      {
        'contributor' => 'openharmony_ci',
        'community' => 'https://gitee.com/openharmony',
        'repo' => nil
      }
    end

    let(:repo_tag) do
      {
        'contributor' => 'Kubernetes Submit Queue',
        'community' => 'https://github.com/kubernetes',
        'repo' => 'https://github.com/kubernetes/kubernetes'
      }
    end

    it 'applies a common tag to every repository of the platform' do
      contributors =
        described_class.indexed_contributors(
          [common_tag],
          repo_urls: ['https://github.com/pytorch/pytorch']
        )

      expect(contributors).to contain_exactly('openeuler-ci-bot')
    end

    it 'applies a community tag to the repositories of the community' do
      contributors =
        described_class.indexed_contributors(
          [community_tag],
          repo_urls: ['https://gitee.com/openharmony/kernel_liteos_a']
        )

      expect(contributors).to contain_exactly('openharmony_ci')
    end

    it 'does not apply a community tag to repositories of another community' do
      contributors =
        described_class.indexed_contributors(
          [community_tag],
          repo_urls: ['https://gitee.com/mindspore/mindspore']
        )

      expect(contributors).to be_empty
    end

    it 'applies a community tag when the requested community matches' do
      contributors =
        described_class.indexed_contributors(
          [community_tag],
          repo_urls: ['https://gitee.com/mindspore/mindspore'],
          community: 'https://gitee.com/openharmony'
        )

      expect(contributors).to contain_exactly('openharmony_ci')
    end

    it 'applies a repo tag to the repository itself' do
      contributors =
        described_class.indexed_contributors(
          [repo_tag],
          repo_urls: ['https://github.com/kubernetes/kubernetes']
        )

      expect(contributors).to contain_exactly('Kubernetes Submit Queue')
    end

    it 'does not apply a repo tag to a sibling repository' do
      contributors =
        described_class.indexed_contributors(
          [repo_tag],
          repo_urls: ['https://github.com/kubernetes/minikube']
        )

      expect(contributors).to be_empty
    end

    it 'merges every matching tag' do
      contributors =
        described_class.indexed_contributors(
          [common_tag, community_tag, repo_tag],
          repo_urls: ['https://github.com/kubernetes/kubernetes']
        )

      expect(contributors).to contain_exactly('openeuler-ci-bot', 'Kubernetes Submit Queue')
    end

    it 'ignores documents without a contributor' do
      contributors =
        described_class.indexed_contributors(
          [{ 'contributor' => nil, 'community' => nil, 'repo' => nil }],
          repo_urls: ['https://github.com/pytorch/pytorch']
        )

      expect(contributors).to be_empty
    end
  end

  describe '.mapping' do
    it 'keeps the fields owned by the data pre-processing pipeline' do
      expect(described_class.mapping['properties'].keys)
        .to include('community', 'contributor', 'platform_type', 'repo', 'uuid')
    end
  end
end
